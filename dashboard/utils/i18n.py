def resolve_lang(selected: str) -> str:
    s = (selected or "en").strip()
    if s in ("kk", "en", "ru"):
        return s
    if s in ("Қазақша", "Kazakh", "KZ"):
        return "kk"
    if s in ("Русский", "Russian", "RU"):
        return "ru"
    return "en"


