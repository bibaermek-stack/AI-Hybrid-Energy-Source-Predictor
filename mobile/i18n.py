def get_text(lang: str, key: str, default: str = "", **fmt) -> str:
    """String for `key` in `lang` (kk fallback), formatted with `fmt` if given."""
    entry = STRINGS.get(key)
    if entry is None:
        text = default or key
    else:
        text = entry[1] if lang == "en" else entry[0]
    return text.format(**fmt) if fmt else text
